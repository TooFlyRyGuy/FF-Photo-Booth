set local search_path to pg_catalog;
with pubns as (select oid from pg_namespace where nspname='public'),
ext_objs as (select objid from pg_depend where deptype='e'),
rels as (select c.* from pg_class c where c.relnamespace=(select oid from pubns) and c.oid not in (select objid from ext_objs)),
q as (
select 10 sec, e.extname::text k, format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname) ddl
  from pg_extension e join pg_namespace n on n.oid=e.extnamespace where e.extname not in ('plpgsql')
union all
select 20, t.typname, format('CREATE TYPE %s AS ENUM (%s);', t.oid::regtype, (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid=t.oid))
  from pg_type t where t.typnamespace=(select oid from pubns) and t.typtype='e'
union all
select 30, c.relname, format(E'CREATE TABLE %s (%s%s\n);', c.oid::regclass,
  (select string_agg(format(E'\n  %I %s%s%s%s', a.attname, format_type(a.atttypid,a.atttypmod),
     case when a.attcollation<>0 and a.attcollation<>t.typcollation then ' COLLATE '||(select quote_ident(collname) from pg_collation where oid=a.attcollation) else '' end,
     case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY' when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end ||
     case when a.attgenerated='s' then ' GENERATED ALWAYS AS ('||pg_get_expr(d.adbin,d.adrelid)||') STORED' when d.adbin is not null then ' DEFAULT '||pg_get_expr(d.adbin,d.adrelid) else '' end,
     case when a.attnotnull then ' NOT NULL' else '' end), ',' order by a.attnum)
   from pg_attribute a join pg_type t on t.oid=a.atttypid left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
   where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped),
  coalesce((select string_agg(format(E',\n  CONSTRAINT %I %s', conname, pg_get_constraintdef(oid)), '' order by case contype when 'p' then 0 when 'u' then 1 else 2 end, conname)
   from pg_constraint where conrelid=c.oid and contype in ('p','u','c','x')),''))
  from rels c where c.relkind in ('r','p')
union all
select 40, conrelid::regclass::text||'.'||conname, format('ALTER TABLE ONLY %s ADD CONSTRAINT %I %s;', conrelid::regclass, conname, pg_get_constraintdef(oid))
  from pg_constraint where contype='f' and conrelid in (select oid from rels)
union all
select 50, ic.relname, pg_get_indexdef(i.indexrelid)||';'
  from pg_index i join pg_class ic on ic.oid=i.indexrelid where i.indrelid in (select oid from rels)
  and not exists (select 1 from pg_constraint k where k.conindid=i.indexrelid and k.conrelid=i.indrelid and k.contype in ('p','u','x'))
union all
select 60, p.oid::regprocedure::text, pg_get_functiondef(p.oid)||';'
  from pg_proc p where p.pronamespace=(select oid from pubns) and p.prokind in ('f','p') and p.oid not in (select objid from ext_objs)
union all
select 70, c.oid::text||' '||c.relname, format(E'CREATE VIEW %s%s AS\n%s', c.oid::regclass, case when c.reloptions is not null then ' WITH ('||array_to_string(c.reloptions,', ')||')' else '' end, pg_get_viewdef(c.oid))
  from rels c where c.relkind='v'
union all
select 80, t.tgrelid::regclass::text||'.'||t.tgname, pg_get_triggerdef(t.oid)||';'
  from pg_trigger t join pg_proc p on p.oid=t.tgfoid where not t.tgisinternal and (t.tgrelid in (select oid from rels) or p.pronamespace=(select oid from pubns))
union all
select 90, c.relname, format('ALTER TABLE %s ENABLE ROW LEVEL SECURITY;', c.oid::regclass)||case when c.relforcerowsecurity then format(E'\nALTER TABLE %s FORCE ROW LEVEL SECURITY;', c.oid::regclass) else '' end
  from rels c where c.relkind in ('r','p') and c.relrowsecurity
union all
select 100, n.nspname||'.'||c.relname||'.'||pol.polname, format('CREATE POLICY %I ON %s AS %s FOR %s TO %s%s%s;', pol.polname, pol.polrelid::regclass,
  case when pol.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
  case pol.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
  case when pol.polroles='{0}' then 'public' else (select string_agg(quote_ident(rolname),', ' order by rolname) from pg_roles where oid=any(pol.polroles)) end,
  case when pol.polqual is not null then E'\n  USING ('||pg_get_expr(pol.polqual,pol.polrelid)||')' else '' end,
  case when pol.polwithcheck is not null then E'\n  WITH CHECK ('||pg_get_expr(pol.polwithcheck,pol.polrelid)||')' else '' end)
  from pg_policy pol join pg_class c on c.oid=pol.polrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname in ('public','storage')
union all
select 110, c.relname, format('REVOKE ALL ON %s %s FROM PUBLIC, anon, authenticated, service_role;', case when c.relkind='S' then 'SEQUENCE' else 'TABLE' end, c.oid::regclass)
  from rels c where c.relkind in ('r','p','v','m','S')
union all
select 111, c.relname||' '||coalesce(r.rolname,'PUBLIC'), format('GRANT %s ON %s %s TO %s;', string_agg(x.privilege_type, ', ' order by x.privilege_type), case when c.relkind='S' then 'SEQUENCE' else 'TABLE' end, c.oid::regclass, coalesce(quote_ident(r.rolname),'PUBLIC'))
  from rels c cross join lateral aclexplode(c.relacl) x left join pg_roles r on r.oid=x.grantee
  where c.relkind in ('r','p','v','m','S') and (x.grantee=0 or r.rolname in ('anon','authenticated','service_role'))
  group by c.oid, c.relname, c.relkind, r.rolname
union all
select 112, p.oid::regprocedure::text, format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated, service_role;', p.oid::regprocedure)
  from pg_proc p where p.pronamespace=(select oid from pubns) and p.prokind in ('f','p') and p.oid not in (select objid from ext_objs) and p.proacl is not null
union all
select 113, p.oid::regprocedure::text||' '||coalesce(r.rolname,'PUBLIC'), format('GRANT EXECUTE ON FUNCTION %s TO %s;', p.oid::regprocedure, coalesce(quote_ident(r.rolname),'PUBLIC'))
  from pg_proc p cross join lateral aclexplode(p.proacl) x left join pg_roles r on r.oid=x.grantee
  where p.pronamespace=(select oid from pubns) and p.prokind in ('f','p') and p.oid not in (select objid from ext_objs)
  and (x.grantee=0 or r.rolname in ('anon','authenticated','service_role')) and x.privilege_type='EXECUTE'
union all
select 120, c.relname, format('COMMENT ON %s %s IS %L;', case c.relkind when 'v' then 'VIEW' else 'TABLE' end, c.oid::regclass, d.description)
  from rels c join pg_description d on d.objoid=c.oid and d.classoid='pg_class'::regclass and d.objsubid=0 where c.relkind in ('r','p','v')
union all
select 121, c.relname||'.'||a.attname, format('COMMENT ON COLUMN %s.%I IS %L;', c.oid::regclass, a.attname, d.description)
  from rels c join pg_description d on d.objoid=c.oid and d.classoid='pg_class'::regclass and d.objsubid>0 join pg_attribute a on a.attrelid=c.oid and a.attnum=d.objsubid
union all
select 122, p.oid::regprocedure::text, format('COMMENT ON FUNCTION %s IS %L;', p.oid::regprocedure, d.description)
  from pg_proc p join pg_description d on d.objoid=p.oid and d.classoid='pg_proc'::regclass where p.pronamespace=(select oid from pubns) and p.oid not in (select objid from ext_objs)
union all
select 123, t.typname, format('COMMENT ON TYPE %s IS %L;', t.oid::regtype, d.description)
  from pg_type t join pg_description d on d.objoid=t.oid and d.classoid='pg_type'::regclass where t.typnamespace=(select oid from pubns)
union all
select 130, b.id, format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %L, %L, %L) ON CONFLICT (id) DO NOTHING;', b.id, b.name, b.public, b.file_size_limit, b.allowed_mime_types)
  from storage.buckets b
union all
select 140, pt.tablename, format('ALTER PUBLICATION supabase_realtime ADD TABLE %I.%I;', pt.schemaname, pt.tablename)
  from pg_publication_tables pt where pt.pubname='supabase_realtime'
)
select sec, k, ddl from q order by sec, k
