import { AspectRatio } from '../types';
import { resizeImageToAspectRatio } from './imageUtils';
import { supabase } from '../lib/supabase';

export const generateBoothImage = async (
  imageBase64: string,
  promptTemplate: string,
  referenceImageBase64?: string,
  aspectRatio?: AspectRatio,
  modelName?: string,
  resolution?: '1K' | '2K' | '4K'
): Promise<string> => {
  try {
    // Call the Supabase Edge Function to generate the image
    const { data, error } = await supabase.functions.invoke('gemini-generate-image', {
      body: {
        imageBase64,
        promptTemplate,
        referenceImageBase64,
        aspectRatio,
        modelName,
        resolution
      }
    });

    if (error) {
      console.error("Edge Function Error:", error);
      throw new Error(error.message || "Failed to generate image");
    }

    if (!data || !data.success) {
      throw new Error(data?.error || "Failed to generate image");
    }

    let generatedImage = data.generatedImage;

    if (!generatedImage) {
      throw new Error("No image generated by the model.");
    }

    // Apply client-side aspect ratio resizing if needed
    if (aspectRatio && aspectRatio !== 'square') {
      console.log(`🖼️ Resizing generated image to ${aspectRatio} aspect ratio...`);
      generatedImage = await resizeImageToAspectRatio(generatedImage, aspectRatio);
    }

    return generatedImage;

  } catch (error) {
    console.error("Gemini Generation Error:", error);
    throw error;
  }
};